import { useState } from 'react';
import { useData } from '../context/DataContext.jsx';
import { Badge, Card, Empty, Page, SearchBox, Select } from '../components/ui.jsx';

export default function Alerts() {
  const { alerts, devices, select } = useData();

  const [q, setQ] = useState('');
  const [severity, setSeverity] = useState('all');
  const [id, setId] = useState(alerts[0]?.id);

  const rows = alerts.filter((alert) =>
    `${alert.id} ${alert.title} ${alert.detail}`
      .toLowerCase()
      .includes(q.trim().toLowerCase())
    && (severity === 'all' || alert.severity === severity),
  );

  const current = rows.find((alert) => alert.id === id) || rows[0];

  const device = devices.find(
    (item) => item.id === current?.deviceId,
  );

  return (
    <Page
      title="Threat alerts"
      subtitle="Alerts generated by the backend's network analysis."
    >
      <div className="flex flex-wrap gap-3">
        <SearchBox
          value={q}
          onChange={setQ}
          placeholder="Search alerts"
        />

        <Select
          label="severities"
          value={severity}
          onChange={setSeverity}
          options={['critical', 'high', 'medium', 'low']}
        />
      </div>

      {!current ? (
        <Card>
          <Empty
            title="No alerts found"
            hint="Run a network analysis or change your search filters."
          />
        </Card>
      ) : (
        <div className="grid gap-4 xl:grid-cols-2">
          <Card>
            {rows.map((alert) => (
              <button
                key={alert.id}
                onClick={() => setId(alert.id)}
                className={`flex w-full cursor-pointer items-center justify-between gap-3 rounded-xl p-3 text-left text-sm ${
                  alert.id === current.id
                    ? 'bg-white/10'
                    : 'hover:bg-white/5'
                }`}
              >
                <span>
                  {alert.title}
                  <span className="block text-xs text-zinc-500">
                    {alert.id} · {alert.time}
                  </span>
                </span>
                <Badge value={alert.severity} />
              </button>
            ))}
          </Card>

          <Card title={`Alert ${current.id}`} className="self-start">
            <Badge value={current.severity} />

            <h3 className="my-3 text-xl">{current.title}</h3>

            <p className="text-sm text-zinc-300">
              {current.detail}
            </p>

            <p className="mt-4 text-xs uppercase text-zinc-500">
              Recommended action
            </p>

            <p className="text-sm">{current.action}</p>

            <p className="mt-4 text-xs text-zinc-500">
              Status: Open. The current backend does not provide alert
              resolution or reopening operations.
            </p>

            {device && (
              <button
                className="btn mt-5"
                onClick={() => select(device.id)}
              >
                View {device.name}
              </button>
            )}
          </Card>
        </div>
      )}
    </Page>
  );
}