class FirestoreLiveSessionRepository(interfaces.LiveSessionRepository):
    def __init__(self):
        self._db = get_firestore_client()

    @_wrap_firestore_errors("create_live_session")
    def create_live_session(
        self,
        session_id: str,
        interface: str,
        subnet: str | None = None,
    ) -> dict:
        now = _now_iso()

        doc = {
            "session_id": session_id,
            "interface": interface,
            "subnet": subnet,
            "status": "created",
            "started_at": None,
            "stopped_at": None,
            "created_at": now,
        }

        self._db.collection("live_sessions").document(session_id).set(doc)
        return self.get_live_session(session_id)

    @_wrap_firestore_errors("update_live_session")
    def update_live_session(
        self,
        session_id: str,
        status: str | None = None,
        started_at: str | None = None,
        stopped_at: str | None = None,
    ) -> bool:
        allowed_statuses = {"created", "running", "stopped", "error"}

        if status is not None and status not in allowed_statuses:
            raise ValueError("Invalid live session status.")

        updates = {}
        if status is not None:
            updates["status"] = status
        if started_at is not None:
            updates["started_at"] = started_at
        if stopped_at is not None:
            updates["stopped_at"] = stopped_at

        if not updates:
            return False

        ref = self._db.collection("live_sessions").document(session_id)

        if not ref.get().exists:
            return False

        ref.update(updates)
        return True

    @_wrap_firestore_errors("save_live_observation")
    def save_live_observation(self, session_id: str, observation: dict) -> bool:
        mac = normalize_mac(observation.get("mac", ""))

        if not mac:
            return False

        now = observation.get("timestamp") or _now_iso()

        doc_ref = (
            self._db.collection("live_sessions")
            .document(session_id)
            .collection("observations")
            .document(mac)
        )

        existing = doc_ref.get()

        if existing.exists:
            old = existing.to_dict()

            protocols = sorted(
                set(old.get("protocols", [])) | set(observation.get("protocols", []))
            )
            ports = sorted(
                set(old.get("ports", [])) | set(observation.get("ports", []))
            )
            dns_names = sorted(
                set(old.get("dns_names", [])) | set(observation.get("dns_names", []))
            )

            doc_ref.update({
                "ip": observation.get("ip") or old.get("ip"),
                "hostname": observation.get("hostname") or old.get("hostname"),
                "protocols": protocols,
                "ports": ports,
                "dns_names": dns_names,
                "source": observation.get("source", "live_network"),
                "last_seen": now,
                "observation_count": old.get("observation_count", 1) + 1,
            })
        else:
            doc_ref.set({
                "session_id": session_id,
                "mac": mac,
                "ip": observation.get("ip"),
                "hostname": observation.get("hostname"),
                "protocols": observation.get("protocols", []),
                "ports": observation.get("ports", []),
                "dns_names": observation.get("dns_names", []),
                "source": observation.get("source", "live_network"),
                "first_seen": now,
                "last_seen": now,
                "observation_count": 1,
            })

        return True

    @_wrap_firestore_errors("get_live_observations")
    def get_live_observations(self, session_id: str) -> list[dict]:
        query = (
            self._db.collection("live_sessions")
            .document(session_id)
            .collection("observations")
            .order_by("last_seen", direction="DESCENDING")
        )
        return [doc.to_dict() for doc in query.stream()]

    @_wrap_firestore_errors("get_live_session")
    def get_live_session(self, session_id: str) -> dict | None:
        ref = self._db.collection("live_sessions").document(session_id)
        snap = ref.get()

        if not snap.exists:
            return None

        session = snap.to_dict()
        session["devices"] = self.get_live_observations(session_id)
        session["device_count"] = len(session["devices"])
        return session

    @_wrap_firestore_errors("get_live_sessions")
    def get_live_sessions(self, limit: int = 50) -> list[dict]:
        query = (
            self._db.collection("live_sessions")
            .order_by("created_at", direction="DESCENDING")
            .limit(limit)
        )
        return [doc.to_dict() for doc in query.stream()]

    @_wrap_firestore_errors("delete_live_session")
    def delete_live_session(self, session_id: str) -> bool:
        ref = self._db.collection("live_sessions").document(session_id)

        if not ref.get().exists:
            return False

        for doc in ref.collection("observations").stream():
            doc.reference.delete()

        ref.delete()
        return True


class FirestoreUserRepository(interfaces.UserRepository):
    def __init__(self):
        self._db = get_firestore_client()

    @_wrap_firestore_errors("create_user")
    def create_user(self, name: str, email: str, password_hash: str) -> dict:
        email = email.strip().lower()
        users_col = self._db.collection("users")

        # Firestore has no UNIQUE constraint; enforce one with a
        # transaction that checks-then-creates, so two concurrent
        # registrations for the same email can't both succeed.
        from firebase_admin import firestore as fa_firestore

        @fa_firestore.transactional
        def _create_in_transaction(transaction):
            existing = list(
                users_col.where("email", "==", email)
                .limit(1)
                .stream(transaction=transaction)
            )

            if existing:
                raise ValueError(
                    "An account with this email already exists."
                )

            user_id = str(uuid.uuid4())
            doc = {
                "id": user_id,
                "name": name,
                "email": email,
                "password_hash": password_hash,
                "created_at": _now_iso(),
            }
            transaction.set(users_col.document(user_id), doc)
            return doc

        transaction = self._db.transaction()
        return _create_in_transaction(transaction)

    @_wrap_firestore_errors("get_user_by_email")
    def get_user_by_email(self, email: str) -> dict | None:
        email = email.strip().lower()
        matches = list(
            self._db.collection("users")
            .where("email", "==", email)
            .limit(1)
            .stream()
        )
        return matches[0].to_dict() if matches else None

    @_wrap_firestore_errors("get_user_by_id")
    def get_user_by_id(self, user_id) -> dict | None:
        snap = self._db.collection("users").document(str(user_id)).get()
        return snap.to_dict() if snap.exists else None

    @_wrap_firestore_errors("create_session")
    def create_session(self, jti: str, user_id, expires_at: int) -> None:
        self._db.collection("sessions").document(jti).set({
            "jti": jti,
            "user_id": str(user_id),
            "expires_at": expires_at,
            "revoked_at": None,
        })

    @_wrap_firestore_errors("get_active_session")
    def get_active_session(self, jti: str, user_id, now_ts: int) -> dict | None:
        snap = self._db.collection("sessions").document(jti).get()

        if not snap.exists:
            return None

        session = snap.to_dict()

        if (
            session.get("user_id") != str(user_id)
            or session.get("revoked_at") is not None
            or session.get("expires_at", 0) <= now_ts
        ):
            return None

        user = self.get_user_by_id(user_id)
        if not user:
            return None

        return {
            "id": user["id"],
            "name": user["name"],
            "email": user["email"],
            "jti": jti,
        }

    @_wrap_firestore_errors("revoke_session")
    def revoke_session(self, jti: str, revoked_at: str) -> None:
        self._db.collection("sessions").document(jti).update(
            {"revoked_at": revoked_at}
        )


def build_repositories() -> interfaces.Repositories:
    return interfaces.Repositories(
        inventory=FirestoreInventoryRepository(),
        analysis=FirestoreAnalysisRepository(),
        observation=FirestoreObservationRepository(),
        alert=FirestoreAlertRepository(),
        live_session=FirestoreLiveSessionRepository(),
        user=FirestoreUserRepository(),
    )
