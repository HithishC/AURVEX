"""
Firestore repository implementations.

Collection layout:

  inventory/{mac}
      One document per approved device. Document ID is the
      normalized MAC address (stable, matches the existing SQLite
      primary key) -- upserts are plain `.set()` calls, so re-running
      an approval is naturally idempotent and duplicate-free.

  analyses/{analysis_id}
      One document per analysis run. Document ID is the existing
      UUID `analysis_id` string already generated by the app, so
      identifiers are preserved across backends.
      Fields: source_name, source_type, device_count, created_at.

  analyses/{analysis_id}/observations/{auto_id}
      Subcollection: the raw per-packet/per-row observations for that
      analysis. Kept in a subcollection (not downloaded by default)
      so reading a list of analyses never pulls observation data --
      satisfies "avoid downloading entire collections for ordinary
      queries".

  analyses/{analysis_id}/results/{auto_id}
      Subcollection: one document per per-device detection result
      (the dict compare_device() returns), same reasoning as above.

  alerts/{auto_id}
      One document per alert, with a `created_at` field used for
      ordering. Reading recent alerts is `order_by(created_at, DESC)
      .limit(n)` -- never a full collection scan client-side.

  live_sessions/{session_id}
      One document per live-discovery session. Document ID is the
      existing UUID `session_id`.

  live_sessions/{session_id}/observations/{mac}
      Subcollection keyed by normalized MAC (mirrors the SQLite
      UNIQUE(session_id, mac) constraint) -- a repeated observation
      for the same MAC is a `.set()`/merge on the same document, so
      duplicates cannot accumulate.

  users/{user_id}
      One document per user. Document ID is a UUID4 string generated
      at creation time (Firestore has no auto-increment integer
      primary key, unlike the SQLite `users.id` column). A unique
      index on `email` is enforced in application code via a
      transaction that checks-then-creates, since Firestore does not
      offer SQL UNIQUE constraints.

      NOTE: shadowshield/auth.py's current JWT code does
      `user_id = int(payload["sub"])`, assuming an integer id. That
      line is NOT touched in this migration pass (auth.py is not yet
      wired to this repository layer -- see repositories/__init__.py
      docstring) but will need updating to accept a string UUID
      before auth.py can actually be cut over to DB_BACKEND=firestore.
      Documenting this now rather than silently working around it.

  (auth) sessions/{jti}
      One document per issued JWT, keyed by its `jti` claim (already
      a unique random token), mirroring the SQLite auth_sessions
      table.

Pagination: `get_analyses`/`get_recent_alerts` accept the same `limit`
parameter as the SQLite versions (interface-compatible). This
implementation additionally accepts an optional `start_after` cursor
(a Firestore DocumentSnapshot or field value) for continuing a
previous page -- this is additive and not part of the shared
interface, since the SQLite side has no equivalent cursor concept.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone

from google.api_core import exceptions as gcloud_exceptions

from . import interfaces
from ..firebase_client import get_firestore_client
from ..normalize import normalize_mac


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _wrap_firestore_errors(operation: str):
    """Decorator-free helper: call fn(), re-raise Firestore/GRPC
    errors as a clear RuntimeError instead of letting a raw
    google.api_core exception escape to API consumers."""

    def decorator(fn):
        def wrapped(*args, **kwargs):
            try:
                return fn(*args, **kwargs)
            except gcloud_exceptions.GoogleAPICallError as exc:
                raise RuntimeError(
                    f"Firestore error during {operation}: {exc}"
                ) from exc

        return wrapped

    return decorator


class FirestoreInventoryRepository(interfaces.InventoryRepository):
    def __init__(self):
        self._db = get_firestore_client()

    @_wrap_firestore_errors("upsert_approved")
    def upsert_approved(self, device: dict) -> None:
        mac = normalize_mac(device.get("mac", ""))

        if not mac:
            raise ValueError("MAC address is required.")

        doc = {
            "mac": mac,
            "ip": device.get("ip", ""),
            "hostname": device.get("hostname", ""),
            "vendor": device.get("vendor", ""),
            "ports": device.get("ports", []) or [],
            "protocols": device.get("protocols", []) or [],
            "allowed_ports": (
                device.get("allowed_ports") or device.get("ports") or []
            ),
            "updated_at": _now_iso(),
        }

        from ..fingerprint import make_fingerprint

        doc["fingerprint"] = make_fingerprint(device)

        self._db.collection("inventory").document(mac).set(doc)

    @_wrap_firestore_errors("delete_approved")
    def delete_approved(self, mac: str) -> bool:
        mac = normalize_mac(mac)
        ref = self._db.collection("inventory").document(mac)

        if not ref.get().exists:
            return False

        ref.delete()
        return True

    @_wrap_firestore_errors("get_approved_inventory")
    def get_approved_inventory(self) -> dict:
        result = {}

        for snap in self._db.collection("inventory").stream():
            result[snap.id] = snap.to_dict()

        return result


class FirestoreAnalysisRepository(interfaces.AnalysisRepository):
    def __init__(self):
        self._db = get_firestore_client()

    @_wrap_firestore_errors("save_analysis")
    def save_analysis(
        self,
        source_name: str,
        source_type: str,
        observations: list[dict],
        results: list[dict],
    ) -> str:
        analysis_id = str(uuid.uuid4())
        now = _now_iso()

        analysis_ref = self._db.collection("analyses").document(analysis_id)

        # Firestore batches cap at 500 writes; chunk explicitly with
        # our own counter (not a library-internal attribute) so a
        # large PCAP's observation/result count can never silently
        # drop writes past that limit.
        BATCH_LIMIT = 450
        batch = self._db.batch()
        pending = 0

        def _flush():
            nonlocal batch, pending
            if pending:
                batch.commit()
            batch = self._db.batch()
            pending = 0

        batch.set(
            analysis_ref,
            {
                "id": analysis_id,
                "source_name": source_name,
                "source_type": source_type,
                "device_count": len(results),
                "created_at": now,
            },
        )
        pending += 1

        obs_col = analysis_ref.collection("observations")
        for obs in observations:
            batch.set(obs_col.document(), dict(obs))
            pending += 1
            if pending >= BATCH_LIMIT:
                _flush()

        result_col = analysis_ref.collection("results")
        for result in results:
            batch.set(result_col.document(), dict(result))
            pending += 1
            if pending >= BATCH_LIMIT:
                _flush()

        if pending:
            batch.commit()

        return analysis_id

    @_wrap_firestore_errors("get_analyses")
    def get_analyses(self, limit: int = 50, start_after=None) -> list[dict]:
        query = (
            self._db.collection("analyses")
            .order_by("created_at", direction="DESCENDING")
            .limit(limit)
        )

        if start_after is not None:
            query = query.start_after(start_after)

        return [snap.to_dict() for snap in query.stream()]

    @_wrap_firestore_errors("get_analysis")
    def get_analysis(self, analysis_id: str) -> dict | None:
        ref = self._db.collection("analyses").document(analysis_id)
        snap = ref.get()

        if not snap.exists:
            return None

        data = snap.to_dict()

        results_query = ref.collection("results").order_by(
            "__name__"
        )
        data["results"] = [doc.to_dict() for doc in results_query.stream()]

        return data


